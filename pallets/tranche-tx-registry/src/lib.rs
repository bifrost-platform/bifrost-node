/// Step within a request's pipeline. Mirrors interface.sol's `RequestStep`.
/// `Requested`/`RequestBridgeExecuted`/`RequestQueued`/
/// `AdapterBridgeExecuted`/`AdapterApplied` are the five values every
/// `FlowVersion::V1` product's `record_request_tx` calls use — plus
/// `Extended`, the version-agnostic escape hatch any later `FlowVersion`
/// funnels its own steps through (see `Extended`'s own doc comment) — six
/// recordable values in total. A request's link to a
/// settlement is recorded elsewhere entirely now (see
/// `SettlementStep::RequestsApproved`'s doc comment for why). Named after the
/// underlying Valuation Contract events wherever one exists 1:1 — `Requested`
/// (`DepositRequested`/`RedeemRequested`, at TrancheManager), `RequestQueued`
/// (`DepositQueued`/`RedeemQueued`, at Valuation), `AdapterApplied`
/// (`Supplied`/`WithdrawRequested`, at the MultichainAdapter) — so a recorder
/// can map "which event did I just see" to "which step do I record" without
/// needing to special-case Hub-vault vs Spoke-vault:
///
/// - `Requested` — the investor's request lands at TrancheManager, wherever
///   the vault is (Hub or Spoke). Opens the `RequestEntries` entry
///   (`investor`/`vault`/`amount`/`order_type`), never carries
///   `adapter_chain_ids` (not knowable yet — even for a Hub-vault request,
///   TrancheManager's event alone doesn't reveal the Adapter decision;
///   that's Valuation's job, one step later).
/// - (only if the vault is on a Spoke chain) `RequestBridgeExecuted` — the
///   *Inbound* leg's Bridge phase, Spoke -> Hub. At most one per request
///   (there's only one vault), so its evidence lives directly on
///   `RequestEntry` rather than per-chain. Never recorded for a Hub-vault
///   request — there's nothing to bridge when the vault is already on Hub.
/// - `RequestQueued` — the moment the request's capital is confirmed at the
///   Hub Valuation Contract and `adapter_chain_ids` becomes known, for
///   **both** Hub-vault and Spoke-vault requests alike. For a Hub-vault
///   request this typically lands in the very same transaction as
///   `Requested` (TrancheManager -> Valuation is a synchronous local call)
///   but is still a separate `record_request_tx` call — for a Spoke-vault
///   request it's the Inbound leg's own Hooks phase, only reachable once
///   `RequestBridgeExecuted` has landed. Evidence recorded on
///   `RequestEntry::queued_tx`.
/// - `AdapterBridgeExecuted`/`AdapterApplied`, once per declared
///   chain — the *Adapter* leg(s), the Hub Valuation Contract pushing the
///   now-arrived capital back out to each remote, actually-weighted
///   MultichainAdapter chain (see `record_request_tx`'s dev notes for exactly
///   which chains belong in that set). Keyed by the extrinsic's own
///   `chain_id` parameter (see `RequestChainEntry`), since a request can need
///   more than one such leg at once. `AdapterApplied` covers both directions
///   — `Supplied` for a deposit, `WithdrawRequested` for a redeem — since
///   both mean the same thing structurally: the Adapter has been notified and
///   acted on this leg. Not every chain in this set needs an
///   `AdapterBridgeExecuted` first: a chain that's *also* the origin vault's
///   own chain, or Hub, can self-fulfill its allocation synchronously (no
///   Bridge leg at all — the Adapter Contract call is local), so
///   `AdapterApplied` alone is valid for it. Such a chain may not even be in
///   `RequestAdapterChains` yet when its `AdapterApplied` evidence arrives —
///   see `Pallet::ensure_adapter_chain_declared`'s doc comment for why this
///   pallet self-declares it on first touch rather than requiring
///   `RequestQueued` to have already listed it.
///
/// A request's link to a settlement — what used to be a sixth step here,
/// `SettlementApproved` — is recorded via `record_settlement_tx`'s
/// `SettlementStep::RequestsApproved` instead, one settlement-wide batch call rather
/// than one `record_request_tx` call per request. See that variant's doc
/// comment for the full mechanism and why it moved; `RequestEntry::settlement_id`/
/// `approved_tx` and `get_request`'s own `settlement_id`/`settled` return values
/// are unaffected by where the write comes from.
///
/// `adapter_chain_ids` (the explicit parameter) is only ever supplied at
/// `RequestQueued` — never at `Requested`, regardless of Hub or Spoke — since
/// `RequestQueued` is precisely the step defined as "the Valuation Contract
/// has now decided the Adapter routing," for both vault locations alike. But
/// `RequestAdapterChains` itself (the actual stored set) can already contain
/// entries before `RequestQueued` ever runs, via the self-declare mechanism
/// above — `RequestQueued` merges its `adapter_chain_ids` into whatever's
/// already there rather than overwriting it.
///
/// `None` and `RequestCompleted` are read-only sentinels, never valid
/// `record_request_tx` input (rejected with `Error::InvalidRequestStep`).
/// Unlike `SettlementStep::Queued` (which `get_settlement` genuinely returns
/// for an untriggered settlement), `None` is never actually returned by
/// `get_request` either — `get_request` reverts outright for a request_id
/// that was never opened, so there's no "not yet requested" state to report —
/// it exists purely so `record_request_tx` has a well-defined way to reject
/// step `0` as invalid input, same as `RequestCompleted`. Named `None` rather
/// than `Queued` specifically to avoid sitting next to `RequestQueued` under a
/// near-identical name while meaning something completely different.
///
/// `RequestCompleted` (renamed from `Completed`) is `get_request`'s own
/// `status` value once `RequestQueued` has landed and every declared Adapter
/// chain's last step has too (or none were declared) — it describes the
/// request's own delivery pipeline finishing, and is deliberately unrelated to
/// whether the settlement it's linked to (see `SettlementStep::RequestsApproved`) has
/// itself settled. `get_request`'s separate `settled` return value answers
/// that second question — the bare name `Completed` read as ambiguous between
/// the two once this pallet started tracking settlement linkage at all, hence
/// the rename.
///
/// 2026-08-20 — this enum used to have a seventh variant, `SettlementApproved`,
/// appended after `RequestCompleted`. Removed outright (not merely deprecated)
/// once `SettlementStep::RequestsApproved` took over recording this evidence: nothing
/// in this pallet's own storage ever encoded a bare `RequestStep` value (see
/// e.g. `RequestEntry`, which stores per-step `Option<TxRecord<_>>` fields
/// directly, never a `step` tag), so removing the trailing variant needs no
/// migration — only `record_request_tx`'s own Call-encoding and
/// `RequestTxRecorded`'s event shape are affected, both fine to break across a
/// coordinated recorder+runtime upgrade (this pallet's `record_*` extrinsics
/// have no caller other than the single registered recorder account — see
/// `Config::RecorderOrigin`).
#[derive(
	Clone,
	Copy,
	Encode,
	Decode,
	DecodeWithMemTracking,
	PartialEq,
	Eq,
	RuntimeDebug,
	TypeInfo,
	MaxEncodedLen,
)]
pub enum RequestStep {
	None,
	Requested,
	RequestBridgeExecuted,
	RequestQueued,
	AdapterBridgeExecuted,
	AdapterApplied,
	/// Renamed from `Completed` — see this enum's doc comment for why. Purely a
	/// Rust/interface.sol identifier rename: enum variant *names* don't affect
	/// SCALE or Solidity ABI encoding (only declaration order/discriminant
	/// does), so this didn't need a migration despite `RequestStep` already
	/// being live.
	RequestCompleted,
	/// 2026-08-24 — the sole, permanent escape hatch for any `FlowVersion`
	/// beyond `V1`. `record_request_tx` never gives this variant its own
	/// step-specific parameters (`opening`/`adapter_chain_ids`/`bridge_status`
	/// must all be `None`, same as every step other than `Requested`); instead
	/// it carries a version-specific payload in the extrinsic's own `extra`
	/// bytes, decoded and validated according to the calling product's
	/// registered `FlowVersion` (see `pallet_tranche_system::RequestFlowVersion`,
	/// read via `ProductInspect::request_flow_version`) — `FlowVersion::V1`
	/// rejects this step outright, since a v1 product's flow is fully covered
	/// by the six steps above.
	///
	/// This is deliberately the *only* variant `RequestStep` will ever gain
	/// after this one: a new flow version's real steps live entirely inside
	/// `extra`'s own version-specific decode target (see
	/// `RequestFlowExtension`/`RequestFlowExtensionV2`), so introducing v3,
	/// v4, ... never needs another `RequestStep` variant, another
	/// `record_request_tx` match arm, or another call_index — only a new
	/// `RequestFlowExtension` variant and a new arm in the `FlowVersion` match
	/// already living inside this one step's own handling.
	Extended,
}

