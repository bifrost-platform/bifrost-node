/// Stored off-chain tx evidence, accepted from the tx recorder's attestation.
/// Mirrors interface.sol's `TxRecord`, except `recorded_at == 0` is not used as
/// an unset sentinel here — that was a Solidity-only workaround for the lack of
/// an `Option` type; on this side, "not yet recorded" is represented directly
/// as `Option<TxRecord<BlockNumber>>` at every storage/query site instead. The
/// precompile boundary (`precompiles/tranche-tx-registry`) is responsible for
/// translating `None` back into a zeroed struct with `recorded_at == 0` when it
/// encodes a response for a Solidity caller.
#[derive(
	Clone,
	Encode,
	Decode,
	DecodeWithMemTracking,
	PartialEq,
	Eq,
	RuntimeDebug,
	TypeInfo,
	MaxEncodedLen,
)]
pub struct TxRecord<BlockNumber> {
	/// EVM chain ID the tx occurred on.
	pub chain_id: ChainId,
	/// Transaction hash on that chain.
	pub tx_hash: H256,
	/// This chain's own block number when the attestation was accepted.
	pub recorded_at: BlockNumber,
}

// ---------------------------------------------------------------------------
// Bridge attempts (retry tracking)
// ---------------------------------------------------------------------------

/// Maximum number of Bridge-phase attempts (one `SocketMessage` resolution —
/// `Executed` or `Reverted` — per attempt) this pallet will record for a
/// single Bridge leg before refusing further ones with
/// `Error::TooManyBridgeAttempts`. CCCP-v2 can roll a Bridge message back
/// (`Reverted`) — when that happens, the refunded contract
/// (`MultichainTrancheManager` for an Inbound/Response leg's refund, since
/// those originate on a Spoke chain; `OrchestratorHub` for an
/// Adapter/Collect/Finalize/Whitelist leg's refund, since those originate on
/// Hub) is expected to expose its own `retry()` entrypoint that resubmits the
/// same Bridge message — this pallet doesn't drive that retry itself, it only
/// records whatever attempts a recorder observed, in order. Sized generously
/// (well above what any real retry policy should ever need) since this bounds
/// on-chain storage growth, not the actual number of retries a bot is allowed
/// to make.
pub const MAX_BRIDGE_ATTEMPTS: u32 = 10;

/// A Bridge-phase message's terminal outcome, per CCCP-v2's `SocketMessage`
/// (see `cccp_primitives::SocketEventStatus` — `None = 0, Requested = 1,
/// Failed = 2, Executed = 3, Reverted = 4, Accepted = 5, Rejected = 6,
/// Committed = 7, Rollbacked = 8`). This pallet only ever cares about the two
/// terminal Bridge-phase outcomes — `Executed` (3) and `Reverted` (4), the
/// direct opposite of `Executed` in that enum — so only those two are
/// represented here, not the full nine-variant enum; `#[codec(index = ...)]`
/// pins each variant's on-chain (and, via the precompile, EVM ABI) byte value
/// to the real `SocketEventStatus` discriminant it corresponds to, so a
/// recorder that already has a raw `SocketEventStatus` byte in hand (from
/// watching the Socket contract directly) can pass it straight through as
/// `bridge_status` without any translation step — and `0` stays free
/// (matching `SocketEventStatus::None`) to unambiguously mean "not
/// applicable" wherever `bridge_status` is sentinel-gated by `step`, with no
/// risk of colliding with a genuine status value the way reusing `0` for one
/// of the two real variants would have. Mirrors interface.sol's raw
/// `uint8 bridge_status`/`BridgeAttempt.status` convention (no Solidity enum
/// — Solidity enums are always contiguously 0-indexed and can't represent
/// this pair's real, non-contiguous values).
#[derive(
	Clone,
	Copy,
	Encode,
	Decode,
	DecodeWithMemTracking,
	PartialEq,
	Eq,
	RuntimeDebug,
	TypeInfo,
	MaxEncodedLen,
)]
pub enum BridgeStatus {
	/// The Bridge message was relayed and successfully executed at its
	/// destination — the leg's Hooks phase (if any) is now reachable.
	#[codec(index = 3)]
	Executed,
	/// The Bridge message was rolled back — the leg never reached its
	/// destination, and the refunded contract (see `MAX_BRIDGE_ATTEMPTS`'s
	/// doc comment) is expected to `retry()` it. Any step gated on this leg
	/// (e.g. `RequestStep::RequestQueued` gated on the Inbound leg) stays
	/// unreachable until some later attempt for the same leg resolves
	/// `Executed`.
	#[codec(index = 4)]
	Reverted,
}

/// One Bridge-phase attempt for a leg — `record_*_tx` appends one of these
/// each time the recorder observes a `SocketMessage` resolve for that leg,
/// `Executed` or `Reverted` alike, rather than overwriting a single evidence
/// slot. Mirrors interface.sol's `BridgeAttempt`.
///
/// A leg's "did this actually complete" question (what every downstream gate
/// — `RequestQueued`, `NavReported`, `NavReceived`, `SettleApplied`,
/// `WhitelistApplied` — checks) is answered by "does *any* attempt in this
/// leg's list have `status == Executed`", not by "is the list non-empty" —
/// see each of those steps' own dev notes. At most one `Executed` attempt can
/// ever exist for a given leg: once one lands, `record_*_tx` refuses to
/// record further attempts for that leg (nothing left to retry).
#[derive(
	Clone,
	Encode,
	Decode,
	DecodeWithMemTracking,
	PartialEq,
	Eq,
	RuntimeDebug,
	TypeInfo,
	MaxEncodedLen,
)]
pub struct BridgeAttempt<BlockNumber> {
	pub status: BridgeStatus,
	pub tx: TxRecord<BlockNumber>,
}

/// Shorthand for a leg's full attempt list — every Bridge-phase evidence
/// field in this pallet (`RequestEntry::bridge_attempts`,
/// `RequestChainEntry::bridge_attempts`,
/// `SettlementChainEntry::{collect,response,finalize}_bridge_attempts`,
/// `WhitelistEntry::bridge_attempts`) uses this same shape. An empty list
/// means "no attempt observed yet" (the pre-existing `None`-equivalent
/// sentinel); a non-empty list with no `Executed` entry means "attempted,
/// currently reverted, awaiting retry" — read-side callers (`get_request`/
/// `get_settlement`/`get_whitelist`) distinguish the two only by inspecting
/// the list itself, since this pallet doesn't track a separate "awaiting
/// retry" flag (see this pallet's `docs/tranche-tx-registry/CHANGELOG.md`
/// entry on why that's left to the frontend to render).
pub type BridgeAttempts<BlockNumber> =
	BoundedVec<BridgeAttempt<BlockNumber>, ConstU32<MAX_BRIDGE_ATTEMPTS>>;

// ---------------------------------------------------------------------------
// Flow versioning
// ---------------------------------------------------------------------------
//
// A product's tx flow (the fixed sequence of `record_*_tx` steps its recorder
// is expected to submit) is pinned once, at that product's own registration,
// and never changes for its lifetime — see `pallet_tranche_system::FlowVersion`'s
// doc comment (that pallet owns the `FlowVersion` type itself, and the
// `RequestFlowVersion`/`SettlementFlowVersion` storage recording it per
// product, per pipeline — this pallet only ever reads it, via
// `pallet_tranche_system::ProductInspect::request_flow_version`/
// `settlement_flow_version`). This lets a genuinely new flow (a product
// needing steps beyond what `RequestStep`'s fixed five cover) be introduced
// without touching how any already-live product is recorded: `RequestStep`
// itself, and every match arm under it in `record_request_tx`, stay frozen
// forever; a new flow's own steps live entirely behind the single
// `RequestStep::Extended` escape hatch, opaque to every `FlowVersion::V1`
// product. See `RequestStep::Extended`'s and `RequestFlowExtension`'s doc
// comments for the full mechanism.

/// Maximum length, in bytes, of `record_request_tx`'s `extra` parameter —
/// only ever populated for `step == RequestStep::Extended`, `None` for every
/// other step. Sized generously for whatever a future flow version's own
/// SCALE-encoded payload turns out to need; bounds storage growth and this
/// extrinsic's weight (linear in `extra`'s length — see `WeightInfo::record_request_tx`),
/// not any real protocol limit.
pub const MAX_REQUEST_EXTRA_LEN: u32 = 1024;

