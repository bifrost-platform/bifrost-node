/// Step within the settlement pipeline. Mirrors interface.sol's
/// `SettlementStep`. `Queued`/`Triggered`/`Settled` are the three states
/// `get_settlement`'s own `status` moves through —
/// `Queued` (not yet triggered), `Triggered` (triggered, awaiting
/// completion), `Settled` (every chain has reached *its own* terminal step —
/// `SettleApplied` if it's in `SettlementFinalizeChains`, otherwise
/// `NavReceived`, since a chain that's Collect/Response-only, i.e.
/// has an Adapter but no vault, never gets a Finalize leg to begin with — see
/// `record_settlement_tx`'s dev notes). The middle six describe one chain's
/// own progress instead — a Collect/Response/Finalize leg crossed with a
/// Bridge/Hooks phase, flattened into this same enum so a single `step`
/// parameter can select any of them. The three Bridge-phase values are
/// suffixed `Executed` (generic Socket-message evidence, nothing more
/// specific to name them after); the three Hooks-phase values are instead
/// named after the underlying Contract event each one's evidence actually
/// is — `NavReported` (TrancheManager, Collect leg), `NavReceived`
/// (Valuation, Response leg), `SettleApplied` (TrancheManager, Finalize
/// leg) — same event-name-mirroring convention as `RequestStep`'s
/// `RequestQueued`/`AdapterApplied`. `Queued` and `Settled` are read-only
/// sentinels and must never be accepted as `record_settlement_tx`'s
/// extrinsic input (rejected with `Error::InvalidSettlementStep`) — nine
/// recordable values in total (`Triggered`, `RequestsApproved`, the six leg
/// steps, plus `Extended` — see that variant's own doc comment).
///
/// A settlement that needs no cross-chain action at all is represented by
/// `Triggered` with both `collect_response_chain_ids` and `finalize_chain_ids`
/// empty — no separate step value needed for this: `Triggered` no longer
/// requires either set to be non-empty (unlike an earlier version of this
/// pallet, which had one combined `spoke_chain_ids`), so both empty alone
/// unambiguously means "nothing to collect/respond/finalize" to every read
/// path via vacuous truth — `get_settlement` already reports this correctly
/// with no special-casing.
///
/// `RequestsApproved` (2026-08-20) is declared right after `NavReceived` — where it
/// actually fires in the real pipeline (see below) — rather than appended at
/// the end: unlike `RequestStep` (whose `record_request_tx`/`step` parameter
/// is itself SCALE-decoded off submitted extrinsic bytes, so discriminant
/// order genuinely had to stay append-only there), nothing in this pallet's
/// own storage ever encodes a raw `SettlementStep` value, and the EVM-facing
/// `step: uint8` the recorder actually submits is translated through the
/// precompile's own hand-maintained `decode_settlement_step` mapping, not a
/// derive-based cast — so this enum's *declaration* order is free to match
/// the real pipeline for readability, independent of whatever numbering the
/// ABI happens to expose.
///
/// Records evidence for every `request_id` Valuation approved into this
/// settlement, in one batch — replaces what used to be a per-request
/// `RequestStep::SettlementApproved` step on `record_request_tx` (one
/// `record_request_tx` call per approved request). The underlying Valuation
/// Contract event changed from firing once per request
/// (`DepositApproved`/`RedeemApproved`) to firing once per settlement
/// (`DepositsApproved`/`RedeemsApproved`, each carrying an array of approved
/// items), so the recorder now only needs one `record_settlement_tx` call —
/// carrying every approved `request_id` from that one event — instead of one
/// call per request; for a Multichain product this fires at essentially the
/// same moment as before (right after every one of the settlement's
/// `collect_response_chain_ids` has reported NAV, i.e. `NavReceived`), just
/// batched — but for a `SingleChain` SYNC product, Valuation emits
/// `DepositsApproved`/`RedeemsApproved` *before* `Settled`, so this step can
/// genuinely land before `Triggered` for the same `settlement_id`.
/// Deliberately has **no** `SettlementTriggers` precondition (unlike every
/// leg step) precisely because of that — the old per-request
/// `RequestStep::SettlementApproved` this replaced never required Trigger to
/// have landed first either, and adding that requirement here would have
/// broken the SingleChain SYNC ordering. Like `Triggered`,
/// `RequestsApproved` is settlement-wide rather than chain-scoped: `spoke_chain_id`
/// MUST be `0` and both `collect_response_chain_ids`/`finalize_chain_ids`
/// MUST be empty for it, same as `Triggered` — but unlike `Triggered`, its own
/// dedicated `request_ids` parameter is what MUST be non-empty instead (see
/// `record_settlement_tx`'s dev notes for the full sentinel-gating table).
/// Per-entry amounts/price the underlying `ApprovedItem` array may carry
/// aren't recorded here — this pallet only ever tracks tx evidence and the
/// request<->settlement linkage, never settlement financials (those live in
/// `pallet-tranche-investments`).
///
/// Writes the exact same fields `RequestStep::SettlementApproved` used to,
/// for every `request_id` in the batch: `RequestEntry::settlement_id`/
/// `approved_tx`, plus a link into `SettlementRequests` — see that storage's
/// doc comment for why this pallet keeps its own copy of the linkage. A
/// `request_id` already recorded (from an earlier `RequestsApproved` call for the
/// same settlement) fails that entry with `Error::RequestStepAlreadyRecorded`,
/// same as calling the old per-request step twice — since a batch is atomic,
/// this rolls back the whole call, same rationale as
/// `pallet_tranche_investments::record_investment_approvals`'s duplicate
/// handling. Also opportunistically closes each request out of
/// `InvestorActiveRequests` immediately if its settlement's completion
/// condition has already landed by the time this call runs (see
/// `Pallet::try_close_request`) — same race this step's per-request
/// predecessor already had to handle.
#[derive(
	Clone,
	Copy,
	Encode,
	Decode,
	DecodeWithMemTracking,
	PartialEq,
	Eq,
	RuntimeDebug,
	TypeInfo,
	MaxEncodedLen,
)]
pub enum SettlementStep {
	Queued,
	Triggered,
	CollectBridgeExecuted,
	NavReported,
	ResponseBridgeExecuted,
	NavReceived,
	RequestsApproved,
	FinalizeBridgeExecuted,
	SettleApplied,
	Settled,
	/// 2026-08-24 — this pipeline's own escape hatch, same mechanism and same
	/// "the only variant this enum will ever gain again" guarantee as
	/// `RequestStep::Extended` (see that variant's doc comment for the full
	/// rationale). Unlike `RequestStep::Extended`, which is always scoped to
	/// the one request it's recorded against, `Extended` here can be either
	/// settlement-wide or chain-scoped, mirrored by the same
	/// `spoke_chain_id`-presence convention every other step here already
	/// uses: `spoke_chain_id == None` routes the decoded `extra` payload into
	/// `SettlementExtension` (settlement-wide — the `Triggered`/
	/// `RequestsApproved` role), `spoke_chain_id == Some` routes it into the
	/// named chain's own `SettlementChainEntry::extension` (chain-scoped —
	/// the six leg steps' role). `collect_response_chain_ids`/
	/// `finalize_chain_ids`/`request_ids` must all be `None` either way — this
	/// step's payload lives entirely in `extra`, decoded according to
	/// `product_id`'s registered `pallet_tranche_system::SettlementFlowVersion`
	/// (read via `ProductInspect::settlement_flow_version`, independent of
	/// `RequestFlowVersion` — see that storage's doc comment for why each
	/// pipeline versions separately). `FlowVersion::V1` rejects this step
	/// outright, same as `RequestStep::Extended` does for a v1 product's
	/// request pipeline.
	Extended,
}

