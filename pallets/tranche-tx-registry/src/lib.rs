/// `EnsureOrigin` that accepts only a signed origin matching the account
/// currently stored in `TxRecorder`. Unlike
/// `pallet_tranche_investments::EnsureValuation` (which checks a
/// precompile-constructed custom `Origin` variant), this checks an ordinary
/// signed extrinsic directly against pallet storage — same pattern as
/// `pallet_tranche_permissions::grant_permission`'s `ProductAdmins` check, just
/// promoted to a reusable `EnsureOrigin` impl since every `record_*` extrinsic
/// needs the identical check.
/// Wire as `type RecorderOrigin = pallet_tranche_tx_registry::EnsureTxRecorder<Runtime>`
/// in the runtime — see `Config::RecorderOrigin`.
pub struct EnsureTxRecorder<T>(PhantomData<T>);

impl<OuterOrigin, T> frame_support::traits::EnsureOrigin<OuterOrigin> for EnsureTxRecorder<T>
where
	T: pallet::pallet::Config,
	OuterOrigin: Into<Result<frame_system::RawOrigin<T::AccountId>, OuterOrigin>>
		+ From<frame_system::RawOrigin<T::AccountId>>,
{
	type Success = T::AccountId;

	fn try_origin(o: OuterOrigin) -> Result<Self::Success, OuterOrigin> {
		o.into().and_then(|raw| match raw {
			frame_system::RawOrigin::Signed(who)
				if pallet::pallet::TxRecorder::<T>::get().as_ref() == Some(&who) =>
			{
				Ok(who)
			},
			raw => Err(OuterOrigin::from(raw)),
		})
	}

	#[cfg(feature = "runtime-benchmarks")]
	fn try_successful_origin() -> Result<OuterOrigin, ()> {
		let recorder = pallet::pallet::TxRecorder::<T>::get().ok_or(())?;
		Ok(OuterOrigin::from(frame_system::RawOrigin::Signed(recorder)))
	}
}
