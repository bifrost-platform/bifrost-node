/// Opaque request identifier, generated by the Valuation Contract — only unique
/// within a product's own namespace. Same underlying type as
/// `pallet_tranche_investments::RequestId`; declared locally rather than
/// imported so this pallet has no hard dependency on tranche-investments (see
/// interface.sol's DRAFT note on why the two precompiles were split apart).
pub type RequestId = H256;

/// Opaque settlement-cycle identifier, generated by the Valuation Contract —
/// only unique within a product's own namespace. Same underlying type as
/// `pallet_tranche_investments::SettlementId`, declared locally for the same
/// reason as `RequestId` above.
pub type SettlementId = U256;

/// EVM chain ID. Bare `u64`, matching `pallet_tranche_system::VaultId::chain_id`
/// — no dedicated newtype exists elsewhere in this pallet family.
pub type ChainId = u64;

/// Maximum number of spoke chains a single settlement can register in
/// `SettlementSpokeChains`. Reuses pallet-tranche-system's
/// `MAX_ADAPTERS_PER_MULTICHAIN_ADAPTER` rather than defining a fresh bound —
/// a settlement's spoke-chain fan-out is ultimately bounded by how many
/// chains a product's own MultichainAdapters span, same rationale as
/// `pallet_tranche_investments::MAX_ALLOCATIONS` reusing
/// `MAX_MULTICHAIN_ADAPTERS`.
pub const MAX_SPOKE_CHAINS: u32 = pallet_tranche_system::MAX_ADAPTERS_PER_MULTICHAIN_ADAPTER;

// ---------------------------------------------------------------------------
// TxRecord
// ---------------------------------------------------------------------------

/// Stored off-chain tx evidence, accepted from the tx recorder's attestation.
/// Mirrors interface.sol's `TxRecord`, except `recorded_at == 0` is not used as
/// an unset sentinel here — that was a Solidity-only workaround for the lack of
/// an `Option` type; on this side, "not yet recorded" is represented directly
/// as `Option<TxRecord<BlockNumber>>` at every storage/query site instead. The
/// precompile boundary (`precompiles/tranche-tx-registry`) is responsible for
/// translating `None` back into a zeroed struct with `recorded_at == 0` when it
/// encodes a response for a Solidity caller.
#[derive(
	Clone,
	Encode,
	Decode,
	DecodeWithMemTracking,
	PartialEq,
	Eq,
	RuntimeDebug,
	TypeInfo,
	MaxEncodedLen,
)]
pub struct TxRecord<BlockNumber> {
	/// EVM chain ID the tx occurred on.
	pub chain_id: ChainId,
	/// Transaction hash on that chain.
	pub tx_hash: H256,
	/// This chain's own block number when the attestation was accepted.
	pub recorded_at: BlockNumber,
}

